#!/usr/bin/env bun
/**
 * One-command setup for a fresh deploy.
 *
 *   bun run setup                 # write .dev.vars, push secrets, deploy
 *   bun run setup -- --no-deploy  # secrets only
 *
 * It never overwrites a value that already exists in `.dev.vars`, so re-running
 * it is safe. Secrets are printed nowhere; the file is written with mode 0600.
 */

import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const VARS_PATH = join(ROOT, '.dev.vars');
const argv = process.argv.slice(2);
const deploy = !argv.includes('--no-deploy');

/** Secrets the Worker reads at runtime. Everything else stays local. */
const WORKER_SECRETS = ['APP_PASSWORD', 'APP_SECRET', 'SHARE_TOKEN', 'AI_API_KEY', 'SUPADATA_API_KEY', 'GITHUB_TOKEN'];

/** Generated on first run if missing. */
const GENERATED = ['APP_PASSWORD', 'APP_SECRET', 'SHARE_TOKEN', 'KEYSTORE_PASS'];

/** Written into .dev.vars even when empty, so the file documents itself. */
const OPTIONAL = ['AI_API_KEY', 'SUPADATA_API_KEY', 'GITHUB_TOKEN', 'SHARE_ENDPOINT'];

const HEADER = [
  '# Generated by `bun run setup`. Never commit this file.',
  '# Regenerate or change values by editing it and re-running the script.',
  '',
].join('\n');

function randomSecret(): string {
  return randomBytes(24).toString('base64url');
}

/** Values copied from .dev.vars.example must never become a deployed secret. */
function isPlaceholder(value: string | undefined): boolean {
  if (!value) return true;
  return /^replace-with|^changeme$|^<.*>$/.test(value.trim());
}

function parseVars(text: string): Map<string, string> {
  const vars = new Map<string, string>();
  for (const line of text.split(/\r?\n/)) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (match) vars.set(match[1], match[2]);
  }
  return vars;
}

function serialize(vars: Map<string, string>): string {
  const known = new Set([...GENERATED, ...OPTIONAL]);
  const body = [...known].map((key) => `${key}=${vars.get(key) ?? ''}`).join('\n');
  const extra = [...vars].filter(([key]) => !known.has(key)).map(([key, value]) => `${key}=${value}`);
  return `${HEADER}${body}${extra.length ? `\n\n# Kept from your previous file\n${extra.join('\n')}` : ''}\n`;
}

function wrangler(args: string[], input?: string) {
  const local = join(ROOT, 'node_modules', '.bin', 'wrangler');
  const [command, commandArgs] = existsSync(local) ? [local, args] : ['bunx', ['wrangler', ...args]];
  return spawnSync(command, commandArgs, {
    cwd: ROOT,
    input,
    stdio: [input === undefined ? 'inherit' : 'pipe', 'inherit', 'inherit'],
  });
}

function main(): void {
  const existing = existsSync(VARS_PATH) ? parseVars(readFileSync(VARS_PATH, 'utf8')) : new Map<string, string>();
  const vars = new Map(existing);
  const created: string[] = [];

  for (const key of GENERATED) {
    if (isPlaceholder(vars.get(key))) {
      vars.set(key, randomSecret());
      created.push(key);
    }
  }
  for (const key of OPTIONAL) {
    if (!vars.has(key)) vars.set(key, '');
  }

  writeFileSync(VARS_PATH, serialize(vars), { mode: 0o600 });
  chmodSync(VARS_PATH, 0o600);

  console.log(`Wrote ${VARS_PATH}`);
  if (created.length) console.log(`  generated: ${created.join(', ')}`);
  const skipped = [...existing.keys()].filter((key) => {
    const value = existing.get(key);
    return Boolean(value) && !isPlaceholder(value);
  });
  if (skipped.length) console.log(`  kept existing: ${skipped.join(', ')}`);

  if (isPlaceholder(vars.get('APP_PASSWORD'))) {
    console.error('\nAPP_PASSWORD is empty, so the app would be unusable. Edit .dev.vars and re-run.');
    process.exit(1);
  }

  console.log('\nChecking Wrangler login...');
  const whoami = wrangler(['whoami']);
  if (whoami.status !== 0) {
    console.error('\nWrangler is not logged in. Run `bunx wrangler login` first, then re-run `bun run setup`.');
    process.exit(1);
  }

  const secrets: Record<string, string> = {};
  for (const key of WORKER_SECRETS) {
    const value = vars.get(key);
    if (value) secrets[key] = value;
  }

  const bulkPath = join(tmpdir(), `xbv-secrets-${process.pid}.json`);
  writeFileSync(bulkPath, JSON.stringify(secrets), { mode: 0o600 });
  console.log(`\nUploading ${Object.keys(secrets).join(', ')} as Worker secrets...`);

  let uploaded = wrangler(['secret', 'bulk', bulkPath]);
  let deployedAlready = false;

  // `secret bulk` cannot target a Worker that does not exist yet, which is the
  // normal first-run case: create it with a deploy, then retry.
  if (uploaded.status !== 0) {
    console.log('\nThe Worker does not exist yet, so deploying it first...');
    const first = wrangler(['deploy']);
    if (first.status !== 0) {
      console.error('\nDeploy failed. Fix the error above and re-run `bun run setup`.');
      process.exit(1);
    }
    deployedAlready = true;
    uploaded = wrangler(['secret', 'bulk', bulkPath]);
  }

  try {
    unlinkSync(bulkPath);
  } catch {
    // The temp file is only readable by this user; leaving it is not fatal.
  }

  if (uploaded.status !== 0) {
    console.error(
      [
        '',
        'Uploading secrets failed. Set them by hand with:',
        ...Object.keys(secrets).map((key) => `  bunx wrangler secret put ${key}`),
        '',
        'The values are in .dev.vars.',
      ].join('\n'),
    );
    process.exit(1);
  }

  if (!deploy || deployedAlready) {
    if (deployedAlready) console.log('\nSecrets set. They apply immediately, no redeploy needed.');
    else console.log('\nSecrets set. Deploy when ready:\n  bunx wrangler deploy');
    if (deployedAlready) printNextSteps();
    return;
  }

  console.log('\nDeploying...');
  const deployed = wrangler(['deploy']);
  if (deployed.status !== 0) {
    console.error('\nDeploy failed. Fix the error above and re-run `bunx wrangler deploy`.');
    process.exit(1);
  }

  printNextSteps();
}

function printNextSteps(): void {
  console.log(
    [
      '',
      'Done. Next steps:',
      '  1. Open the printed workers.dev URL and log in with APP_PASSWORD.',
      '  2. Optional: add a custom domain in the Cloudflare dashboard, or set "routes"',
      '     in wrangler.jsonc.',
      '  3. Optional: build the Android share APK with android/build.sh',
      '     (needs SHARE_TOKEN, SHARE_ENDPOINT, and KEYSTORE_PASS in .dev.vars).',
    ].join('\n'),
  );
}

main();
