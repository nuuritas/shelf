import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseChangelog, type ChangelogEntry } from '../src/changelog.ts';

/**
 * Regenerates `src/changelog-data.ts` from `CHANGELOG.md`.
 *
 * The Worker cannot read a file at runtime, so the parsed file is committed as
 * a plain literal. `test/changelog.test.js` compares the two byte for byte, so
 * a bullet added without running this script fails `node --test`.
 */
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CHANGELOG_FILE = join(ROOT, 'CHANGELOG.md');
export const DATA_FILE = join(ROOT, 'src', 'changelog-data.ts');

const HEADER = '/** Generated by `bun run changelog` from CHANGELOG.md. Do not edit by hand. */';

/** The whole module as a string, so a test can compare it with the file. */
export function renderChangelogData(entries: ChangelogEntry[]): string {
  const body = entries
    .map((entry) => {
      const bullets = entry.bullets
        .map((bullet) => `      ${JSON.stringify(bullet)},`)
        .join('\n');
      return `  {
    date: ${JSON.stringify(entry.date)},
    bullets: [
${bullets}
    ],
  },`;
    })
    .join('\n');

  const list = body ? `[\n${body}\n]` : '[]';

  return `${HEADER}
import type { ChangelogEntry } from './changelog.ts';

export const CHANGELOG: ChangelogEntry[] = ${list};
`;
}

/** Writes the module. Running it twice produces the same bytes. */
export async function generateChangelogData(): Promise<void> {
  const markdown = await readFile(CHANGELOG_FILE, 'utf8');
  await writeFile(DATA_FILE, renderChangelogData(parseChangelog(markdown)), 'utf8');
}

const isMain = (import.meta as ImportMeta & { main?: boolean }).main === true;
if (isMain) await generateChangelogData();
